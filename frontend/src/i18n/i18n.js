export const MISSING_EN_TRANSLATION = '[English translation unavailable]';

export function hasEnglishTranslation(text) {
  return Object.hasOwn(EN, text);
}

/** Translates an Uzbek-Latin string into the given language. */
export function translate(lang, text) {
  if (text == null || text === '') {
    return text;
  }
  if (lang === 'ru') {
    return RU[text] ?? text;
  }
  if (lang === 'en') {
    return EN[text] ?? MISSING_EN_TRANSLATION;
  }
  if (lang === 'uzc') {
    return toCyrillic(text);
  }
  return text;
}
